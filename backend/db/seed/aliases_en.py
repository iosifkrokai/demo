"""English names for the objects we hold, read from the local OSM extract into a sidecar.
The dataset has no column for a translated name, so the file lets the retrieval alias
signal answer an English query without a schema change; optionally applied to ``place_aliases``."""

from __future__ import annotations

import importlib
import json
import os
import re
from collections.abc import Iterable
from pathlib import Path
from typing import Any

from core.config import DEFAULT_DSN
from core.paths import PLACE_ALIASES_EN_JSON
from db.connection import connect
from db.seed.datasets import collect_records, default_datasets, norm_name

from .geofence import inside_project_area

DSN = os.environ.get("DATABASE_URL", DEFAULT_DSN)

PBF = os.environ.get("OSM_PBF")

_OSM_REF = re.compile(r"^osm(?:_poi)?:(node|way|relation)/(\d+)$")

_SOURCE = "osm"


def _osmium() -> Any:
    """Import pyosmium on demand — not a declared dependency, so applying the written
    file needs no extract reader.
    """
    try:
        return importlib.import_module("osmium")
    except ImportError as exc:
        raise RuntimeError(
            "стадия aliases-en требует pyosmium (osmium): он не объявлен в pyproject — "
            "установите его отдельно (pip install osmium) или используйте уже записанный "
            "place_aliases_en.json"
        ) from exc


_DESCRIPTION = (
    "English names the OSM objects we hold answer to, read from the local extract's "
    "`name:en` tag. The 14-column dataset has no column for a translated name, so it "
    "travels beside the dataset the way place_aliases.json does: the seed reads this "
    "file (db/seed/datasets.py) and writes each name into place_aliases(locale='en'), "
    "where the retrieval alias signal matches an English query without a schema change. "
    "Generated by `python -m db.seed aliases-en` from the PBF — do not edit by hand."
)


def osm_targets(records: Iterable[dict[str, Any]]) -> dict[str, dict[str, Any]]:
    """The OSM identity (``node/123``) behind each record's ``source_url``, limited to
    points inside the project area. An identity two records claim is kept once, in
    dataset order, so the file does not depend on heap order."""
    targets: dict[str, dict[str, Any]] = {}
    for record in records:
        match = _OSM_REF.match(str(record.get("source_url") or ""))
        if not match:
            continue
        lat, lon = record.get("lat"), record.get("lon")
        if not inside_project_area(lat, lon):
            continue
        identity = f"{match.group(1)}/{match.group(2)}"
        targets.setdefault(
            identity,
            {
                "source_url": str(record["source_url"]),
                "name": str(record.get("name") or ""),
                "lat": lat,
                "lon": lon,
            },
        )
    return targets


def alias_for(name_en: str, name_ru: str) -> str | None:
    """The one English name to keep from an OSM ``name:en`` semicolon list: the first
    candidate that differs from the row's own name after normalisation, or ``None``.
    """
    key = norm_name(name_ru)
    for part in name_en.split(";"):
        candidate = part.strip()
        if candidate and norm_name(candidate) != key:
            return candidate
    return None


def collect_names(pbf_path: Path, targets: dict[str, Any]) -> tuple[dict[str, str], int]:
    """One pass over the extract: the ``name:en`` of every object we hold, and how many
    objects carry the tag. Identities are exact, so another object type with the same
    number stays out, and the key filter runs in C++."""
    osmium: Any = _osmium()
    wanted = set(targets)
    base_handler = osmium.SimpleHandler

    class Collector(base_handler):
        """Reads only the tag it needs, and counts every object that has it."""

        def __init__(self) -> None:
            super().__init__()
            self.found: dict[str, str] = {}
            self.with_en = 0

        def _keep(self, kind: str, obj: Any) -> None:
            value: str | None = None
            for tag in obj.tags:
                if tag.k == "name:en" and tag.v.strip():
                    value = tag.v.strip()
                    break
            if value is None:
                return
            self.with_en += 1
            key = f"{kind}/{obj.id}"
            if key in wanted:
                self.found.setdefault(key, value)

        def node(self, n: Any) -> None:
            self._keep("node", n)

        def way(self, w: Any) -> None:
            self._keep("way", w)

        def relation(self, r: Any) -> None:
            self._keep("relation", r)

    collector = Collector()
    collector.apply_file(str(pbf_path), filters=[osmium.filter.KeyFilter("name:en")])
    return collector.found, collector.with_en


def build_entries(
    targets: dict[str, dict[str, Any]], found: dict[str, str]
) -> tuple[list[dict[str, Any]], dict[str, int]]:
    """The sidecar's entries in ``source_url`` order; identities with no record and names
    the row already carries are dropped.
    """
    stats = {"matched": 0, "written": 0, "repeats_ru": 0, "multiple_candidates": 0}
    entries: list[dict[str, Any]] = []
    known = [identity for identity in found if identity in targets]
    for identity in sorted(known, key=lambda i: targets[i]["source_url"]):
        target = targets[identity]
        stats["matched"] += 1
        raw = found[identity]
        if len([part for part in raw.split(";") if part.strip()]) > 1:
            stats["multiple_candidates"] += 1
        alias = alias_for(raw, target["name"])
        if alias is None:
            stats["repeats_ru"] += 1
            continue
        entries.append(
            {
                "source_url": target["source_url"],
                "locale": "en",
                "names": [alias],
                "source": _SOURCE,
            }
        )
        stats["written"] += 1
    return entries, stats


def write_document(path: Path, entries: list[dict[str, Any]]) -> None:
    """Write the sidecar file as ``place_aliases.json`` is shaped: description + entries."""
    document = {"description": _DESCRIPTION, "places": entries}
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(document, ensure_ascii=False, indent=2, sort_keys=False) + "\n",
        encoding="utf-8",
    )


def run_stage(
    *,
    pbf_path: Path | None = None,
    out: Path | None = None,
    data_dir: Path | None = None,
    records: list[dict[str, Any]] | None = None,
    apply: bool = False,
    dsn: str | None = None,
) -> dict[str, Any]:
    """Generate the English-alias sidecar, and optionally apply it to ``place_aliases``
    inside one transaction the caller commits.
    """
    pbf = pbf_path or (Path(PBF) if PBF else None)
    if pbf is None:
        raise RuntimeError("стадии aliases-en нужен PBF: передайте pbf_path или задайте OSM_PBF")
    path = out or PLACE_ALIASES_EN_JSON

    rows: list[dict[str, Any]]
    if records is not None:
        rows = records
    else:
        datasets = default_datasets()
        if data_dir is not None:
            datasets = [d.with_data_dir(data_dir) for d in datasets]
        rows = collect_records(datasets)["records"]

    targets = osm_targets(rows)
    found, with_en = collect_names(pbf, targets)
    entries, counts = build_entries(targets, found)

    write_document(path, entries)
    stats: dict[str, Any] = {
        **counts,
        "targets": len(targets),
        "pbf_with_name_en": with_en,
    }
    print(
        f"объектов с name:en в экстракте: {with_en}, наших: {len(found)}, "
        f"точек-кандидатов {len(targets)}, записано алиасов: {counts['written']} -> {path.name}"
    )

    if apply:
        from . import pipeline

        with connect(dsn or DSN, timeout=None) as conn:
            result = pipeline.apply_place_aliases(conn, path)
            conn.commit()
        stats["db"] = result
    return stats
