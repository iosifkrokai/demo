"""Street hints for the unnamed stops and toilets, measured from the local extract: the
nearest *named* road tells two label-only rows apart, and a sidecar is written only for
rows the answer is unambiguous for over the road classes a walk uses."""

from __future__ import annotations

import importlib
import json
import math
import os
import re
from collections.abc import Iterable, Sequence
from dataclasses import dataclass
from itertools import pairwise
from pathlib import Path
from typing import Any

from core.config import DEFAULT_DSN
from core.paths import PLACE_STREETS_JSON

from .datasets import collapse, collect_records, default_datasets
from .osm_tags import is_fallback_name

PBF = os.environ.get("OSM_PBF")
DSN = os.environ.get("DATABASE_URL", DEFAULT_DSN)

SOURCE = "osm_street"

STREET_HIGHWAY_CLASSES = frozenset(
    {
        "motorway",
        "trunk",
        "primary",
        "secondary",
        "tertiary",
        "unclassified",
        "residential",
        "living_street",
        "pedestrian",
    }
)

TARGET_CATEGORIES = frozenset({"остановка транспорта", "туалет"})

MEASURE_THRESHOLDS_M = (15.0, 25.0, 50.0, 100.0)

STREET_THRESHOLD_M = 15.0
STREET_AMBIGUITY_M = 40.0

_LAT_M_PER_DEG = 111_320.0
_GRID_STEP_DEG = 0.004
_MIN_ROAD_POINTS = 2

_ROAD_NUMBER = re.compile(r"^[A-Za-zА-Яа-яЁёІіЎў]{1,4}[\s\-–]?\d{1,5}(?:-[A-Za-zА-Яа-я]{1,3})?$")

_DESCRIPTION = (
    "Street hints for the transport stops and toilets OSM leaves unnamed, measured from "
    "the local extract — the nearest named road to the point, not a geocoder's guess. "
    "Each entry names the row (source_url), the generated label it extends (name), the "
    "street chosen (street), the distance to it (dist_m) and where it came from "
    "(source). Only rows the answer is unambiguous for are written: the road is the "
    "nearest of all roads, stands within 15 m, is a name rather than a road number, and "
    "no differently named road is within 40 m. The seed overlays it on the row's name "
    "after the dataset upsert, so the CSV's own label cannot win the name back. "
    "Generated by `python -m db.seed streets` from the PBF — do not edit by hand."
)


@dataclass(frozen=True)
class Road:
    """A highway way as a polyline, the label it answers to, and whether that label is a
    name: ``named`` is False for a road tagged with a number alone, where ``name`` holds it.
    """

    name: str
    named: bool
    points: tuple[tuple[float, float], ...]


@dataclass(frozen=True)
class StreetAnswer:
    """Why a point's street is what it is: ``ok`` | ``ambiguous`` | ``number`` | ``none``."""

    status: str
    street: str | None
    dist_m: float | None
    rival: tuple[str, float] | None


def _osmium() -> Any:
    """Import pyosmium on demand — not a declared dependency, so applying the written
    file needs no extract reader.
    """
    try:
        return importlib.import_module("osmium")
    except ImportError as exc:
        raise RuntimeError(
            "стадия streets требует pyosmium (osmium): он не объявлен в pyproject — "
            "установите его отдельно (pip install osmium) или используйте уже записанный "
            "place_streets.json"
        ) from exc


def pick_road_name(tags: dict[str, str]) -> str | None:
    """The road's name in Russian first, then whatever spelling the source carries."""
    for key in ("name:ru", "name", "name:be"):
        value = (tags.get(key) or "").strip()
        if value:
            return value
    return None


def looks_like_road_number(label: str | None) -> bool:
    """True for a road *number* («М6», «Р42», «Н6131», «МКАД-2») — which road, not what street."""
    return bool(label) and bool(_ROAD_NUMBER.match(label.strip()))


def collect_roads(pbf_path: Path) -> list[Road]:
    """The street-class roads as polylines, in two C++-filtered passes: ways first, then
    only the node ids they name resolved to coordinates.
    """
    osmium: Any = _osmium()
    base = osmium.SimpleHandler
    ways: dict[int, tuple[str, bool, list[int]]] = {}
    wanted: set[int] = set()

    class Ways(base):
        """The ways of the street classes that carry a name or a number."""

        def way(self, w: Any) -> None:
            if w.tags.get("highway") not in STREET_HIGHWAY_CLASSES:
                return
            tags = {t.k: t.v for t in w.tags}
            name = pick_road_name(tags)
            ref = (tags.get("ref") or "").strip()
            if not name and not ref:
                return
            refs = [node.ref for node in w.nodes]
            if len(refs) < _MIN_ROAD_POINTS:
                return
            ways[w.id] = (name or ref, bool(name), refs)
            wanted.update(refs)

    Ways().apply_file(str(pbf_path), filters=[osmium.filter.KeyFilter("highway")])

    coords: dict[int, tuple[float, float]] = {}

    class Nodes(base):
        """Only the nodes the kept ways are built from."""

        def node(self, n: Any) -> None:
            coords[n.id] = (n.location.lat, n.location.lon)

    Nodes().apply_file(str(pbf_path), filters=[osmium.filter.IdFilter(sorted(wanted))])

    roads: list[Road] = []
    for way_id in sorted(ways):
        name, named, refs = ways[way_id]
        points = tuple(coords[ref] for ref in refs if ref in coords)
        if len(points) >= _MIN_ROAD_POINTS:
            roads.append(Road(name=name, named=named, points=points))
    return roads


def _segments(points: Sequence[tuple[float, float]]) -> Iterable[tuple[Any, Any]]:
    """Every consecutive pair of a polyline."""
    return pairwise(points)


def _point_segment_m(
    lat: float, lon: float, start: tuple[float, float], end: tuple[float, float]
) -> float:
    """Metres from the point to the closest spot on one segment, on a local flat grid."""
    scale = math.cos(math.radians(lat)) * _LAT_M_PER_DEG
    x1, y1 = (start[1] - lon) * scale, (start[0] - lat) * _LAT_M_PER_DEG
    x2, y2 = (end[1] - lon) * scale, (end[0] - lat) * _LAT_M_PER_DEG
    dx, dy = x2 - x1, y2 - y1
    span = dx * dx + dy * dy
    if span == 0.0:
        return math.hypot(x1, y1)
    t = max(0.0, min(1.0, -(x1 * dx + y1 * dy) / span))
    return math.hypot(x1 + t * dx, y1 + t * dy)


def _road_distance_m(road: Road, lat: float, lon: float) -> float:
    """Metres from the point to the closest spot on the road's polyline."""
    return min(_point_segment_m(lat, lon, start, end) for start, end in _segments(road.points))


def _cell(lat: float, lon: float) -> tuple[int, int]:
    return math.floor(lat / _GRID_STEP_DEG), math.floor(lon / _GRID_STEP_DEG)


def _segment_cells(
    start: tuple[float, float], end: tuple[float, float]
) -> Iterable[tuple[int, int]]:
    """Every grid cell the segment's bounding box touches."""
    rows = sorted((int(start[0] / _GRID_STEP_DEG), int(end[0] / _GRID_STEP_DEG)))
    cols = sorted((int(start[1] / _GRID_STEP_DEG), int(end[1] / _GRID_STEP_DEG)))
    for row in range(rows[0], rows[1] + 1):
        for col in range(cols[0], cols[1] + 1):
            yield row, col


class StreetIndex:
    """Roads bucketed into a coarse grid so a point only measures its neighbourhood; the
    cell size guarantees the point's cell and its eight neighbours cover every threshold.
    """

    def __init__(self, roads: Sequence[Road]) -> None:
        self._roads = tuple(roads)
        cells: dict[tuple[int, int], set[int]] = {}
        for position, road in enumerate(self._roads):
            for start, end in _segments(road.points):
                for key in _segment_cells(start, end):
                    cells.setdefault(key, set()).add(position)
        self._cells = cells

    def candidates(self, lat: float, lon: float, *, rings: int = 1) -> list[Road]:
        """The roads whose cells touch the point's cell or its ``rings`` neighbours."""
        row, col = _cell(lat, lon)
        found: set[int] = set()
        for i in range(row - rings, row + rings + 1):
            for j in range(col - rings, col + rings + 1):
                found |= self._cells.get((i, j), set())
        return [self._roads[position] for position in sorted(found)]


def rank_roads(roads: Iterable[Road], lat: float, lon: float) -> list[tuple[float, Road]]:
    """The roads sorted by distance to the point, ties broken by name then start point."""
    return sorted(
        ((_road_distance_m(road, lat, lon), road) for road in roads),
        key=lambda item: (item[0], item[1].name, item[1].points[0]),
    )


def answer_from_ranked(
    ranked: Sequence[tuple[float, Road]],
    *,
    threshold_m: float = STREET_THRESHOLD_M,
    ambiguity_m: float = STREET_AMBIGUITY_M,
) -> StreetAnswer:
    """The street a point stands on, or why none can be named: the road must be the nearest
    of all roads with no differently named road within ``ambiguity_m``; a number-only road
    is refused, since «Остановка (Р42)» says which road, not what street."""
    if not ranked or ranked[0][0] > threshold_m:
        return StreetAnswer("none", None, None, None)
    dist, road = ranked[0]
    if not road.named or looks_like_road_number(road.name):
        return StreetAnswer("number", road.name, dist, None)
    rival = next(
        (
            (other.name, other_dist)
            for other_dist, other in ranked[1:]
            if other.name != road.name and other_dist <= ambiguity_m
        ),
        None,
    )
    if rival is not None:
        return StreetAnswer("ambiguous", road.name, dist, rival)
    return StreetAnswer("ok", road.name, dist, None)


def collect_targets(records: Iterable[dict[str, Any]]) -> list[dict[str, Any]]:
    """The stop and toilet rows still carrying a generated label with no street hint."""
    targets: list[dict[str, Any]] = []
    for record in records:
        if record.get("category") not in TARGET_CATEGORIES:
            continue
        name = str(record.get("name") or "")
        if not is_fallback_name(name) or "(" in name:
            continue
        if record.get("lat") is None or record.get("lon") is None:
            continue
        targets.append(record)
    return targets


def _ranked_for(index: StreetIndex, record: dict[str, Any]) -> list[tuple[float, Road]]:
    lat, lon = float(record["lat"]), float(record["lon"])
    return rank_roads(index.candidates(lat, lon), lat, lon)


def build_entries(
    targets: Sequence[dict[str, Any]],
    index: StreetIndex,
    *,
    threshold_m: float = STREET_THRESHOLD_M,
    ambiguity_m: float = STREET_AMBIGUITY_M,
) -> tuple[list[dict[str, Any]], dict[str, int]]:
    """The sidecar's entries — the ``ok`` rows only — and the status counts behind them."""
    counts = {"ok": 0, "ambiguous": 0, "number": 0, "none": 0}
    entries: list[dict[str, Any]] = []
    for record in sorted(targets, key=lambda r: str(r["source_url"])):
        answer = answer_from_ranked(
            _ranked_for(index, record), threshold_m=threshold_m, ambiguity_m=ambiguity_m
        )
        counts[answer.status] += 1
        if answer.status == "ok" and answer.street is not None and answer.dist_m is not None:
            entries.append(
                {
                    "source_url": str(record["source_url"]),
                    "name": str(record["name"]),
                    "street": answer.street,
                    "dist_m": round(answer.dist_m, 1),
                    "source": SOURCE,
                }
            )
    return entries, counts


def measure(
    targets: Sequence[dict[str, Any]],
    index: StreetIndex,
    *,
    thresholds: Iterable[float] = MEASURE_THRESHOLDS_M,
) -> dict[str, dict[str, int]]:
    """The status counts at each threshold, ambiguity measured at the threshold itself;
    ``got`` is every row with a road inside it, including number-only and ambiguous ones.
    """
    ranked = [(_ranked_for(index, record)) for record in targets]
    out: dict[str, dict[str, int]] = {}
    for threshold in thresholds:
        counts = {"ok": 0, "ambiguous": 0, "number": 0, "none": 0}
        for roads in ranked:
            status = answer_from_ranked(roads, threshold_m=threshold, ambiguity_m=threshold).status
            counts[status] += 1
        counts["got"] = counts["ok"] + counts["ambiguous"] + counts["number"]
        out[f"{threshold:g}"] = counts
    return out


def read_place_street_entries(path: Path | None = None) -> list[dict[str, Any]]:
    """``place_streets.json`` as rows: the label to extend, the street, the distance."""
    source = path or PLACE_STREETS_JSON
    if not source.is_file():
        return []
    data = json.loads(source.read_text(encoding="utf-8"))
    rows: list[dict[str, Any]] = []
    for entry in data.get("places") or []:
        url = str(entry.get("source_url") or "")
        name = str(entry.get("name") or "").strip()
        street = str(entry.get("street") or "").strip()
        if not url or not name or not street:
            continue
        rows.append(
            {
                "source_url": url,
                "name": name,
                "street": street,
                "dist_m": entry.get("dist_m"),
                "source": entry.get("source"),
            }
        )
    return rows


def write_document(path: Path, entries: list[dict[str, Any]]) -> None:
    """Write the sidecar as ``place_aliases.json`` is shaped: description + entries."""
    document = {"description": _DESCRIPTION, "places": entries}
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(document, ensure_ascii=False, indent=2, sort_keys=False) + "\n",
        encoding="utf-8",
    )


def run_stage(
    *,
    pbf_path: Path | None = None,
    out: Path | None = None,
    data_dir: Path | None = None,
    records: list[dict[str, Any]] | None = None,
    apply: bool = False,
    dsn: str | None = None,
) -> dict[str, Any]:
    """Measure every unnamed stop and toilet against the extract, write the sidecar, and
    optionally apply it inside one transaction the caller commits.
    """
    pbf = pbf_path or (Path(PBF) if PBF else None)
    if pbf is None:
        raise RuntimeError("стадии streets нужен PBF: передайте pbf_path или задайте OSM_PBF")
    path = out or PLACE_STREETS_JSON

    rows: list[dict[str, Any]]
    if records is not None:
        rows = records
    else:
        datasets = default_datasets()
        if data_dir is not None:
            datasets = [d.with_data_dir(data_dir) for d in datasets]
        rows, _, _ = collapse(collect_records(datasets)["records"])

    targets = collect_targets(rows)
    print(f"целей (строк без имени): {len(targets)}")
    roads = collect_roads(pbf)
    named = sum(1 for road in roads if road.named)
    print(f"дорог в экстракте: {len(roads)} (с именем {named}, с номером {len(roads) - named})")
    index = StreetIndex(roads)

    table = measure(targets, index)
    for threshold, counts in table.items():
        print(
            f"  порог {threshold:>3} м: получили улицу {counts['got']}, "
            f"неоднозначных {counts['ambiguous']}, номер вместо имени {counts['number']}, "
            f"ничего {counts['none']}"
        )

    entries, counts = build_entries(targets, index)
    for record in sorted(targets, key=lambda r: str(r["source_url"]))[:20]:
        answer = answer_from_ranked(_ranked_for(index, record))
        shown = answer.street or "—"
        distance = f"{answer.dist_m:.1f} м" if answer.dist_m is not None else "—"
        print(
            f"    {record['source_url']:<24} {record['lat']},{record['lon']} "
            f"-> {shown!r} ({distance}) [{answer.status}]"
        )

    write_document(path, entries)
    stats: dict[str, Any] = {"targets": len(targets), "roads": len(roads), **counts}
    print(
        f"записано строк: {counts['ok']} из {len(targets)} "
        f"(однозначных), неоднозначных {counts['ambiguous']}, "
        f"на номере дороги {counts['number']}, ничего рядом {counts['none']} -> {path.name}"
    )

    if apply:
        from db.connection import connect

        from . import pipeline

        with connect(dsn or DSN, timeout=None) as conn:
            result = pipeline.apply_place_streets(conn, path)
            conn.commit()
        stats["db"] = result
    return stats
