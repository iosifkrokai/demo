"""Fortifications and named boulders, re-read from the local extract.

The corrected tag map (`osm_tags.sight_tag_to_category`) types `military=bunker`, a fort
name, `natural=stone` and a bare `historic=ruins` differently from the Overpass snapshot
`places_osm_raw.csv` holds: pillboxes sat in `замок`, named stones in `архитектура`, and
a watermill's ruin read as a castle. This stage reads the extract once, re-derives each
object's category, and writes the correction two ways — a sidecar
(`place_categories.json`) that re-labels the rows the snapshot already holds, and a
dataset (`places_finds.csv`) that adds the fortifications and boulders it never held.
Run `python -m db.seed.finds --pbf <extract>` to regenerate both.
"""

from __future__ import annotations

import argparse
import csv
import importlib
import json
import os
import re
from collections.abc import Iterable
from pathlib import Path
from typing import Any

from core.paths import PLACE_CATEGORIES_JSON, PLACES_DIR

from . import osm_tags, taxonomy
from .datasets import BBOX, COLUMNS, FINDS_DATASET, collect_records, default_datasets
from .geofence import inside_project_area
from .overpass import resolve_district

PBF = os.environ.get("OSM_PBF")

SOURCE_PREFIX = "osm:"

KEYS = ("historic", "military", "natural")

ADDED_CODES = ("укрепление", "валун")

_CYRILLIC = re.compile(r"[А-Яа-яЁёІіЎў]")

Row = dict[str, str | None]

_DESCRIPTION = (
    "Category corrections for the OSM rows the corrected tag map re-derives: the "
    "fortifications, named boulders and ruins that `places_osm_raw.csv` typed by "
    "`historic=ruins`. Each entry names the row (source_url) and the category the "
    "extract's own tags give it. The seed overlays it after the dataset upsert, so the "
    "snapshot's category cannot win it back. Generated by `python -m db.seed.finds` "
    "from the PBF — do not edit by hand."
)


def _osmium() -> Any:
    """Import pyosmium on demand — it is not a declared dependency."""
    try:
        return importlib.import_module("osmium")
    except ImportError as exc:
        raise RuntimeError(
            "стадии finds нужен pyosmium (osmium): он не объявлен в pyproject — "
            "установите его отдельно (uv pip install osmium) или используйте уже "
            "записанные places_finds.csv и place_categories.json"
        ) from exc


def line_center(points: Iterable[tuple[float, float]]) -> tuple[float, float] | None:
    """The bounding-box centre of a way, the point Overpass calls its ``center``."""
    lat_lon = list(points)
    if not lat_lon:
        return None
    lons = [lon for lon, _ in lat_lon]
    lats = [lat for _, lat in lat_lon]
    return (min(lats) + max(lats)) / 2, (min(lons) + max(lons)) / 2


def element_to_row(element: dict[str, Any], category: str) -> Row | None:
    """One OSM element → a 14-column places row, or None when it is not a row here."""
    tags = element.get("tags") or {}
    center = element.get("center") or {}
    lat, lon = center.get("lat"), center.get("lon")
    if lat is None or lon is None:
        return None
    name = osm_tags.sight_name(tags)
    if not name or not _CYRILLIC.search(name):
        return None
    if not inside_project_area(float(lat), float(lon)):
        return None
    if not (
        BBOX["south"] <= float(lat) <= BBOX["north"] and BBOX["west"] <= float(lon) <= BBOX["east"]
    ):
        return None

    osm_type = element.get("type") or "node"
    return {
        "name": name,
        "category": category,
        "district": resolve_district(float(lat), float(lon), tags),
        "town": (tags.get("addr:city") or tags.get("addr:village") or "").strip(),
        "lat": f"{lat:.6f}",
        "lon": f"{lon:.6f}",
        "blurb": "",
        "fun_fact": "",
        "fun_facts": "[]",
        "opening_hours": tags.get("opening_hours", ""),
        "ticket_price": osm_tags.ticket_price_of(tags),
        "visit_minutes": str(taxonomy.visit_minutes(category)),
        "links": "[]",
        "source_url": f"{SOURCE_PREFIX}{osm_type}/{element.get('id')}",
    }


def collect_elements(pbf_path: Path) -> list[dict[str, Any]]:
    """One C++-filtered pass over the extract, the elements in the order ``osm_tags`` maps.

    ``KeyFilter`` runs in C++, so Python sees only objects carrying `historic`, `military`
    or `natural` — the keys the two new categories and the ruins fall-through read. Node
    locations are resolved for the ways' centres in a second filtered pass, never a
    per-object Python callback over the whole file.
    """
    osmium: Any = _osmium()
    base = osmium.SimpleHandler
    elements: list[dict[str, Any]] = []
    way_refs: dict[int, list[int]] = {}

    class Ways(base):
        def node(self, way_node: Any) -> None:
            lat, lon = way_node.location.lat, way_node.location.lon
            if lat == 0.0 and lon == 0.0:
                return
            tags = {tag.k: tag.v for tag in way_node.tags}
            elements.append(
                {
                    "type": "node",
                    "id": way_node.id,
                    "center": {"lat": lat, "lon": lon},
                    "tags": tags,
                }
            )

        def way(self, way: Any) -> None:
            tags = {tag.k: tag.v for tag in way.tags}
            way_refs[way.id] = [node.ref for node in way.nodes]
            elements.append({"type": "way", "id": way.id, "tags": tags})

    Ways().apply_file(str(pbf_path), filters=[osmium.filter.KeyFilter(*KEYS)])

    needed = sorted({ref for refs in way_refs.values() for ref in refs})
    coords: dict[int, tuple[float, float]] = {}

    class Nodes(base):
        def node(self, node: Any) -> None:
            coords[node.id] = (node.location.lat, node.location.lon)

    Nodes().apply_file(str(pbf_path), filters=[osmium.filter.IdFilter(needed)])

    for element in elements:
        if element["type"] != "way":
            continue
        points = [coords[ref] for ref in way_refs.get(element["id"], []) if ref in coords]
        center = line_center((lon, lat) for lat, lon in points)
        if center is not None:
            element["center"] = {"lat": center[0], "lon": center[1]}
    return [element for element in elements if "center" in element]


def split_objects(
    elements: Iterable[dict[str, Any]], existing: dict[str, dict[str, Any]]
) -> tuple[list[Row], list[dict[str, Any]]]:
    """Re-derive every object's category, split into new rows and re-labelled rows.

    An object the committed datasets already hold is a *correction* — the row keeps its
    name, district and prose, and only its category changes; the category is part of the
    text a vector was built from, so that row's vector is dropped and rebuilt. An object
    they do not hold is a *row*, but only for the two new categories: the stage is not a
    re-fetch, and inventing rows for every monastery the snapshot missed is what this
    deliberately does not do.
    """
    rows: list[Row] = []
    corrections: list[dict[str, Any]] = []
    for element in elements:
        tags = element.get("tags") or {}
        category = osm_tags.sight_tag_to_category(tags)
        if category is None:
            continue
        element_id = f"{SOURCE_PREFIX}{element['type']}/{element['id']}"
        held = existing.get(element_id)
        if held is not None:
            if held["category"] != category and held["_category_source"] == "auto":
                corrections.append(
                    {
                        "source_url": element_id,
                        "category": category,
                        "visit_minutes": taxonomy.visit_minutes(category),
                    }
                )
        elif category in ADDED_CODES:
            row = element_to_row(element, category)
            if row is not None:
                rows.append(row)
    rows.sort(key=lambda row: str(row["source_url"]))
    corrections.sort(key=lambda entry: entry["source_url"])
    return rows, corrections


def read_place_category_entries(path: Path | None = None) -> list[dict[str, Any]]:
    """``place_categories.json`` as rows: the source_url and the category to lay on it."""
    source = path or PLACE_CATEGORIES_JSON
    if not source.is_file():
        return []
    data = json.loads(source.read_text(encoding="utf-8"))
    entries: list[dict[str, Any]] = []
    for entry in data.get("places") or []:
        url = str(entry.get("source_url") or "").strip()
        category = str(entry.get("category") or "").strip()
        if not url or not category:
            continue
        entries.append(
            {
                "source_url": url,
                "category": category,
                "visit_minutes": entry.get("visit_minutes"),
            }
        )
    return entries


def write_dataset(rows: list[Row], path: Path) -> None:
    """Write the new rows in the pipe-separated format, header commented."""
    path.parent.mkdir(parents=True, exist_ok=True)
    fieldnames = list(COLUMNS)
    with path.open("w", encoding="utf-8", newline="") as fh:
        fh.write("# " + "|".join(fieldnames) + "\n")
        writer = csv.DictWriter(fh, fieldnames=fieldnames, delimiter="|", quoting=csv.QUOTE_MINIMAL)
        writer.writerows(rows)


def write_sidecar(entries: list[dict[str, Any]], path: Path) -> None:
    """Write the corrections as ``place_aliases.json`` is shaped: description + places."""
    document = {"description": _DESCRIPTION, "places": entries}
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(
        json.dumps(document, ensure_ascii=False, indent=2, sort_keys=False) + "\n",
        encoding="utf-8",
    )


def held_records(data_dir: Path | None = None) -> dict[str, dict[str, Any]]:
    """The rows the *other* datasets hold, keyed by source_url.

    This stage's own dataset is left out: a second run would otherwise find the rows it
    wrote last time already committed, count every one of them as a row the datasets hold,
    and rewrite the file empty — and the next seed would apply that, pruning them from the
    database. Its output is not evidence about what the data holds; every other dataset is.
    """
    datasets = default_datasets()
    if data_dir is not None:
        datasets = [ds.with_data_dir(data_dir) for ds in datasets]
    others = [ds for ds in datasets if ds.name != FINDS_DATASET]
    return {r["source_url"]: r for r in collect_records(others)["records"]}


def run_stage(
    *,
    pbf_path: Path | None = None,
    dataset_out: Path | None = None,
    sidecar_out: Path | None = None,
    data_dir: Path | None = None,
) -> dict[str, Any]:
    """Re-classify the extract's fortifications, boulders and ruins into both files."""
    pbf = pbf_path or (Path(PBF) if PBF else None)
    if pbf is None:
        raise RuntimeError("стадии finds нужен PBF: передайте pbf_path или задайте OSM_PBF")

    existing = held_records(data_dir)

    elements = collect_elements(pbf)
    rows, corrections = split_objects(elements, existing)

    dataset_path = dataset_out or PLACES_DIR / "places_finds.csv"
    sidecar_path = sidecar_out or PLACE_CATEGORIES_JSON
    write_dataset(rows, dataset_path)
    write_sidecar(corrections, sidecar_path)
    return {"elements": len(elements), "rows": len(rows), "corrections": len(corrections)}


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="python -m db.seed.finds")
    parser.add_argument("--pbf", type=Path, default=None, help="OSM extract (default $OSM_PBF).")
    parser.add_argument("--out", type=Path, default=None, help="Where the new rows go.")
    parser.add_argument("--sidecar", type=Path, default=None, help="Where the corrections go.")
    parser.add_argument("--data-dir", type=Path, default=None, help="Where the datasets live.")
    args = parser.parse_args(argv)

    stats = run_stage(
        pbf_path=args.pbf,
        dataset_out=args.out,
        sidecar_out=args.sidecar,
        data_dir=args.data_dir,
    )
    print(
        f"[seed] finds: {stats['rows']} новых строк, {stats['corrections']} правок категории "
        f"(объектов в экстракте {stats['elements']})"
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
